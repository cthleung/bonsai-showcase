def test_a_failing_session_keeps_its_files_unread_and_the_rest_still_run(cfg, novel, monkeypatch):
    write(novel, "2026-11-10_15-00-00Z-a.md", specstory(sid=SID, body=user("a") + agent("A.")))
    write(novel, "2026-11-10_15-00-00Z-b.md", specstory(sid=OTHER, body=user("b") + agent("B.")))
    real = cc.build_session

    def flaky(files, *a, **k):
        if files[0].header.session_id == SID:
            raise ValueError("boom")
        return real(files, *a, **k)
    monkeypatch.setattr(cc, "build_session", flaky)
    report = run()
    assert report.counts["failed"] == 1 and report.counts["new"] == 1
    data = json.loads((cfg.state / "cursors" / "claude-code-testhost.json").read_text(encoding="utf-8"))
    assert {v["id"] for v in data["files"].values()} == {OTHER}
    assert "boom" not in (cfg.state / "capture.log").read_text(encoding="utf-8")   # the kind only
    monkeypatch.setattr(cc, "build_session", real)
    assert run().counts["new"] == 1                         # read again on the next run


