def test_quoted_transcript_inside_a_tool_block_doesnt_split_it(cfg, novel):
    fake = ("```text\n_**User (2026-01-01 00:00:00Z)**_\n\nnot a real turn\n\n</details></tool-use>\n"
            "<tool-use data-tool-type=\"read\" data-tool-name=\"Inner\"><details>\n```")
    nested = ('<tool-use data-tool-type="task" data-tool-name="Task"><details>\n<summary>x</summary>\n'
              '<tool-use data-tool-type="read" data-tool-name="Read"><details>\ninner\n</details></tool-use>\n'
              "still inside\n</details></tool-use>\n")
    body = (user("read the old chat")
            + agent('<tool-use data-tool-type="read" data-tool-name="Read"><details>\n<summary>r</summary>\n'
                    f"````text\n{fake}\n````\n</details></tool-use>\n")
            + agent(nested, "2026-11-10 15:01:30Z")
            + agent("Done reading.", "2026-11-10 15:02:00Z"))
