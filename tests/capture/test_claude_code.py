SID = "5e551011-aaaa-4bbb-8ccc-0123456789ab"
OTHER = "0ther000-aaaa-4bbb-8ccc-0123456789ab"


def specstory(sid=SID, kind="Claude Code", body=""):
    return (f"<!-- Generated by SpecStory, Markdown v2.1.0 -->\n\n# 2026-11-10 15:00:00Z\n\n"
            f"<!-- {kind} Session {sid} (2026-11-10 15:00:00Z) -->\n\n{body}")


def user(text, when="2026-11-10 15:00:00Z"):
    return f"_**User ({when})**_\n\n{text}\n\n---\n\n"


def agent(text, when="2026-11-10 15:01:00Z", model="claude-test-1"):
    return f"_**Agent ({model} {when})**_\n\n{text}\n\n"


def tool(name="Bash", output="ok"):
    return (f'<tool-use data-tool-type="shell" data-tool-name="{name}"><details>\n'
            f"<summary>Tool use: **{name}**</summary>\nDo a thing\n\n`ls`\n\n```text\n{output}\n```\n"
            f"</details></tool-use>\n")


BASIC = (user("how do I fix the build?")
         + agent(tool("Bash", "secret build log line"))
         + agent(tool("Read", "a whole file dump"))
         + agent("<think><details><summary>Thought Process</summary>\nThe build needs a clean.\n</details></think>",
                 when="2026-11-10 15:02:00Z")
         + agent("Run `make clean` first.", when="2026-11-10 15:03:00Z")
         + user("thanks", when="2026-11-10 15:10:00Z")
         + agent("Any time.", when="2026-11-10 15:11:00Z"))


@pytest.fixture
def novel(tmp_path, monkeypatch):
    """A repo named Novel with a SpecStory history folder, set as the only input, and marked
    creative in BONSAI_REPO_VISIBILITY."""
    hist = tmp_path / "Novel" / ".specstory" / "history"
    hist.mkdir(parents=True)
    monkeypatch.setenv("BONSAI_SPECSTORY_DIRS", str(hist))
    monkeypatch.setenv("BONSAI_REPO_VISIBILITY", "novel=creative")
    return hist


def load(cfg_env_only=None):
    return config.load().require()


def write(hist: Path, name: str, text: str) -> Path:
    p = hist / name
    p.write_text(text, encoding="utf-8", newline="\n")
    return p


def run(**kw):
    return cc.run(load(), today="2026-11-19", host="testhost", **kw)


def notes_in(cfg, repo="Novel"):
    return sorted((cfg.vault / "3 Resources/chats/claude-code" / repo).glob("*.md"))


def test_one_note_per_session_trimmed(cfg, novel):
    raw = write(novel, "2026-11-10_15-00-00Z-fix-the-build.md", specstory(body=BASIC))
    report = run()
    assert report.counts["new"] == 1
    [path] = notes_in(cfg)
    assert path.name == "2026-11-10 fix the build (5e551011).md"
    meta, body = notes.read_note(path)
    assert meta["source"] == "claude-code" and meta["capture"] == "specstory" and meta["chat_id"] == SID
    assert meta["agent"] == "claude-code" and "host" not in meta and meta["repo"] == "Novel"
    assert "testhost" not in body
    assert meta["visibility"] == "creative"                 # from BONSAI_REPO_VISIBILITY, set by the script
    assert meta["raw"] == raw.as_posix() and meta["message_count"] == 2
    assert meta["model"] == "claude-test-1" and "url" not in meta
    assert "how do I fix the build?" in body and "Run `make clean` first." in body
    assert "*[2 tool calls: Bash, Read]*" in body
    assert "> *thinking:* The build needs a clean." in body
    assert "secret build log line" not in body and "a whole file dump" not in body
    assert "## 2. You (2026-11-10)\n\nthanks\n\n### Claude Code\n\nAny time." in body
    assert not (cfg.state / "raw").exists()                 # nothing copied
    assert "searchable" in body and "resumable" in body


def test_rerun_changes_nothing_and_a_grown_session_rewrites_in_place(cfg, novel):
    raw = write(novel, "2026-11-10_15-00-00Z-fix-the-build.md", specstory(body=BASIC))
    run()
    [path] = notes_in(cfg)
    before = path.read_bytes()
    again = run()
    assert again.read == 0 and path.read_bytes() == before
    (cfg.state / "cursors" / "claude-code-testhost.json").unlink()   # read everything again
    again = cc.run(load(), today="2026-11-20", host="testhost")
    assert again.counts["unchanged"] == 1 and path.read_bytes() == before   # `captured` didn't churn it
    raw.write_text(specstory(body=BASIC + user("one more", "2026-11-12 15:00:00Z")
                             + agent("Sure.", "2026-11-12 15:01:00Z")), encoding="utf-8")
    grown = cc.run(load(), today="2026-11-21", host="testhost")
    assert grown.counts["updated"] == 1
    assert notes_in(cfg) == [path]
    meta, body = notes.read_note(path)
    assert meta["message_count"] == 3 and meta["updated"] == "2026-11-12" and meta["captured"] == "2026-11-21"
    assert "Sure." in body


